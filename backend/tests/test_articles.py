class TestDetail:
    async def test_detail_by_slug_and_id_are_equivalent(
        self, client: AsyncClient, published_article: dict[str, object]
    ) -> None:
        by_slug = await client.get(f"/api/v1/articles/{published_article['slug']}")
        by_id = await client.get(f"/api/v1/articles/{published_article['id']}")
        assert by_slug.status_code == by_id.status_code == 200
        assert by_slug.json()["id"] == by_id.json()["id"]
        assert by_slug.json()["content_md"] == published_article["content_md"]

    async def test_view_count_increments(
        self, client: AsyncClient, published_article: dict[str, object]
    ) -> None:
        before = published_article["view_count"]
        after = (await client.get(f"/api/v1/articles/{published_article['slug']}")).json()[
            "view_count"
        ]
        assert after == before + 1

    async def test_view_does_not_touch_updated_at(
        self, client: AsyncClient, published_article: dict[str, object]
    ) -> None:
        """阅读量变化不是内容修改，不能改 updated_at。

        列上的 ``onupdate`` 对 Core ``update()`` 同样生效，早先没显式钉住它，
        于是**读一次文章就改一次 updated_at**。后果有两个，都是用户可见的：
        后台默认排序 ``sort=updated`` 实际变成「最近被看过的」，热门旧文会压过
        刚编辑过的；sitemap 的 ``<lastmod>`` 每次访问都变，等于告诉爬虫
        全站天天在改。
        """
        first = (await client.get(f"/api/v1/articles/{published_article['slug']}")).json()
        assert first["view_count"] == published_article["view_count"] + 1

        # 再读几次，updated_at 必须纹丝不动
        for _ in range(2):
            later = (await client.get(f"/api/v1/articles/{published_article['slug']}")).json()
        assert later["view_count"] > first["view_count"]
        assert later["updated_at"] == first["updated_at"]

    async def test_like_does_not_touch_updated_at(
        self, client: AsyncClient, published_article: dict[str, object]
    ) -> None:
        """点赞同理：计数变化不该被当成内容更新。"""
        before = (await client.get(f"/api/v1/articles/{published_article['slug']}")).json()
        await client.post(f"/api/v1/articles/{published_article['id']}/like")
        after = (await client.get(f"/api/v1/articles/{published_article['slug']}")).json()
        assert after["updated_at"] == before["updated_at"]

    async def test_editing_does_touch_updated_at(
        self,
        client: AsyncClient,
        published_article: dict[str, object],
        author_headers: dict[str, str],
    ) -> None:
        """反向断言：真正的内容修改必须更新 updated_at，别修过头。"""
        before = (await client.get(f"/api/v1/articles/{published_article['slug']}")).json()
        await client.patch(
            f"/api/v1/articles/{published_article['id']}",
            json={"summary": "改过的摘要"},
            headers=author_headers,
        )
        after = (await client.get(f"/api/v1/articles/{published_article['slug']}")).json()
        assert after["updated_at"] > before["updated_at"]

    async def test_missing_article_returns_404(self, client: AsyncClient) -> None:
        assert (await client.get("/api/v1/articles/no-such-slug")).status_code == 404

    async def test_draft_is_404_for_guest_but_visible_to_author(
        self, client: AsyncClient, author_headers: dict[str, str]
    ) -> None:
        """草稿对访客返回 404 而非 403——403 等于承认"这里有一篇未发布的文章"。"""
        draft = (
            await client.post(
                "/api/v1/articles",
                json=make_article_payload(status="draft"),
                headers=author_headers,
            )
        ).json()

        assert (await client.get(f"/api/v1/articles/{draft['slug']}")).status_code == 404
        owned = await client.get(f"/api/v1/articles/{draft['slug']}", headers=author_headers)
        assert owned.status_code == 200
        assert owned.json()["status"] == "draft"

    async def test_neighbors_follow_publish_order(
        self, client: AsyncClient, author_headers: dict[str, str]
    ) -> None:
        """prev 是更早发布的一篇，next 是更新的一篇，两端为 None。"""
        ids = []
        for index in range(3):
            body = (
                await client.post(
                    "/api/v1/articles",
                    json=make_article_payload(title=f"相邻文章{index}-{unique_suffix()}"),
                    headers=author_headers,
                )
            ).json()
            ids.append(body["id"])

        oldest = (await client.get(f"/api/v1/articles/{ids[0]}")).json()
        assert oldest["prev"] is None
        assert oldest["next"]["id"] == ids[1]

        middle = (await client.get(f"/api/v1/articles/{ids[1]}")).json()
        assert middle["prev"]["id"] == ids[0]
        assert middle["next"]["id"] == ids[2]

        newest = (await client.get(f"/api/v1/articles/{ids[2]}")).json()
        assert newest["prev"]["id"] == ids[1]
        assert newest["next"] is None

    async def test_draft_never_appears_as_neighbor(
        self, client: AsyncClient, author_headers: dict[str, str]
    ) -> None:
        """中间插一篇草稿，前后两篇已发布文章应该直接互为邻居。"""
        first = (
            await client.post(
                "/api/v1/articles", json=make_article_payload(), headers=author_headers
            )
        ).json()
        await client.post(
            "/api/v1/articles",
            json=make_article_payload(status="draft"),
            headers=author_headers,
        )
        third = (
            await client.post(
                "/api/v1/articles", json=make_article_payload(), headers=author_headers
            )
        ).json()

        detail = (await client.get(f"/api/v1/articles/{third['id']}")).json()
        assert detail["prev"]["id"] == first["id"]



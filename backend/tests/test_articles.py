class TestSorting:
    async def _seed_three(self, client: AsyncClient, headers: dict[str, str]) -> None:
        titles = ["第一篇", "第二篇", "第三篇"]
        for index, title in enumerate(titles):
            body = (
                await client.post(
                    "/api/v1/articles",
                    json=make_article_payload(title=title),
                    headers=headers,
                )
            ).json()
            # 用 PATCH 调整阅读量，构造"热度与时间顺序不同"的场景
            if index == 0:
                for _ in range(3):
                    await client.post(f"/api/v1/articles/{body['id']}/like")

    async def test_latest_and_oldest_are_mirror_images(
        self, client: AsyncClient, author_headers: dict[str, str]
    ) -> None:
        await self._seed_three(client, author_headers)
        latest = (await client.get("/api/v1/articles?sort=latest")).json()["items"]
        oldest = (await client.get("/api/v1/articles?sort=oldest")).json()["items"]
        assert [i["id"] for i in latest] == list(reversed([i["id"] for i in oldest]))

    async def test_hottest_sorts_by_view_count(
        self, client: AsyncClient, author_headers: dict[str, str]
    ) -> None:
        ids = []
        for index in range(3):
            body = (
                await client.post(
                    "/api/v1/articles",
                    json=make_article_payload(title=f"热度文章{index}"),
                    headers=author_headers,
                )
            ).json()
            ids.append(body["id"])
        # 给最后一篇（时间上最新）刷最多的阅读量
        for _ in range(3):
            await client.get(f"/api/v1/articles/{ids[-1]}")

        hottest = (await client.get("/api/v1/articles?sort=hottest")).json()["items"]
        assert hottest[0]["id"] == ids[-1]

    async def test_top_article_comes_first_regardless_of_sort(
        self, client: AsyncClient, author_headers: dict[str, str]
    ) -> None:
        """置顶的语义就是"永远在最前面"，否则置顶没有意义。"""
        normal = (
            await client.post(
                "/api/v1/articles", json=make_article_payload(), headers=author_headers
            )
        ).json()
        pinned = (
            await client.post(
                "/api/v1/articles",
                json=make_article_payload(is_top=True),
                headers=author_headers,
            )
        ).json()
        oldest_first = (await client.get("/api/v1/articles?sort=oldest")).json()["items"]
        assert oldest_first[0]["id"] == pinned["id"]
        assert oldest_first[1]["id"] == normal["id"]

    async def test_invalid_sort_enum_rejected(self, client: AsyncClient) -> None:
        response = await client.get("/api/v1/articles?sort=drop_table")
        assert response.status_code == 422


